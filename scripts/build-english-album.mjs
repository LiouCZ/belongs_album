import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const chinese = /[\u3400-\u9fff]/u;
const normalize = (value) => String(value).replace(/\s+/g, " ").trim();

export function translateLines(value, lexicon, missing = new Set()) {
  return String(value).split(/(\r\n|\n|\r)/).map((line, index) => {
    if (index % 2 || !chinese.test(line)) return line;
    const key = normalize(line);
    const translated = lexicon[key];
    if (typeof translated !== "string" || !translated.trim() || chinese.test(translated) || /[\r\n]/.test(translated)) {
      missing.add(key);
      return line;
    }
    return translated;
  }).join("");
}

export function buildEnglishAlbum(directory = root) {
  const window = {};
  const context = vm.createContext({ window });
  const inputs = ["data/items.js", "data/curated-official.js", "reading-layout.js", "locales/en/story.js",
    ...Array.from({ length: 6 }, (_, index) => `locales/en/regular-${2021 + index}.js`)];
  for (const file of inputs) {
    vm.runInContext(fs.readFileSync(path.join(directory, file), "utf8"), context, { filename: file });
  }
  const lexicon = Object.fromEntries(Object.entries({ ...window.BELONGS_EN.text, ...window.BELONGS_EN.regularLines })
    .map(([source, en]) => [normalize(source), en]));
  const missing = new Set();
  const works = {};
  const articles = {};
  const snapshot = (source) => ({ source, en: translateLines(source, lexicon, missing) });
  const regular = [...window.BELONGS_DATA.items, ...window.BELONGS_CURATED.items]
    .filter((item) => !item.releaseType || item.releaseType === "regular");
  for (const item of regular) {
    const id = item.workId || item.id;
    const display = window.BelongsReading.title(item.title, { id, caption: item.caption });
    const fields = { title: item.title, caption: item.caption, heading: display.heading, lead: display.description };
    if (works[id]) {
      for (const [field, source] of Object.entries(fields)) {
        if (works[id][field].source !== source) throw new Error(`${id}.${field}: conflicting source records`);
      }
      continue;
    }
    works[id] = Object.fromEntries(Object.entries(fields).map(([field, source]) => [field, snapshot(source)]));
  }
  for (const article of window.BELONGS_CURATED.articles) {
    for (const work of article.works) {
      if (!works[work.id]) throw new Error(`${work.id}: full-article work is missing from regular items`);
      if (works[work.id].title.source !== work.title) throw new Error(`${work.id}: article and item titles differ`);
      works[work.id].description = snapshot(work.description);
    }
    if (article.theme) articles[article.id] = { theme: snapshot(article.theme.text) };
  }
  if (missing.size) throw new Error(`Missing or invalid English lines (${missing.size}):\n${[...missing].join("\n")}`);
  const content = `// Generated by scripts/build-english-album.mjs. Edit the reviewed year lexicons instead.\n(() => {\n  const en = window.BELONGS_EN ||= {};\n  Object.assign(en.works ||= {}, ${JSON.stringify(works, null, 2)});\n  Object.assign(en.articles ||= {}, ${JSON.stringify(articles, null, 2)});\n})();\n`;
  return { content, workCount: Object.keys(works).length, articleCount: Object.keys(articles).length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    const result = buildEnglishAlbum();
    const target = path.join(root, "locales/en/regular-works.js");
    if (process.argv.includes("--check")) {
      if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== result.content) {
        throw new Error("English album is out of date. Run node scripts/build-english-album.mjs");
      }
    } else {
      fs.writeFileSync(target, result.content);
    }
    console.log(`PASS ${result.workCount} regular works and ${result.articleCount} article themes: complete, source-checked English`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
